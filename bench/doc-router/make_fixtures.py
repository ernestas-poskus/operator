#!/usr/bin/env python3
"""Build the committed fixture set used by `tests/document_router.rs`.

Five small real-world office documents come from Apache Tika's test resources
(Apache-2.0, attributed in `fixtures/ATTRIBUTIONS.md`); the two PDFs are
generated here so the fixture set carries no third-party PDF:

* `note.pdf` — a text PDF (LibreOffice export), exercises the anydoc primary.
* `scanned.pdf` — the same page rasterised through `sips` and re-wrapped as an
  image-only PDF, exercises the OCR fallback path.

`fixtures/manifest.json` records every file's SHA-256, origin and license; the
router test verifies the hashes before converting, so a swapped fixture fails
loudly instead of silently changing what the test proves.

Usage:
  python3 bench/doc-router/make_fixtures.py --corpora <benchmark>/vendor
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
FIXTURES = ROOT / "bench" / "doc-router" / "fixtures"
SOFFICE = "/opt/homebrew/bin/soffice"
SIPS = "/usr/bin/sips"

# Files copied verbatim from Apache Tika's test resources (Apache-2.0).
TIKA_FIXTURES = {
    "office.docx": "tika-parsers/tika-parsers-standard/tika-parsers-standard-modules/tika-parser-microsoft-module/src/test/resources/test-documents/NullHeader.docx",
    "slides.pptx": "tika-parsers/tika-parsers-standard/tika-parsers-standard-modules/tika-parser-microsoft-module/src/test/resources/test-documents/testPPT_masterText.pptx",
    "sheet.xlsx": "tika-parsers/tika-parsers-standard/tika-parsers-standard-modules/tika-parser-microsoft-module/src/test/resources/test-documents/testEXCEL_poi.xlsx",
    "text.rtf": "tika-parsers/tika-parsers-standard/tika-parsers-standard-modules/tika-parser-microsoft-module/src/test/resources/test-documents/testRTFBoldItalic.rtf",
    "document.odt": "tika-parsers/tika-parsers-standard/tika-parsers-standard-modules/tika-parser-miscoffice-module/src/test/resources/test-documents/testODT_svgTitleInStyledSpan.odt",
}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def build_generated() -> None:
    work = FIXTURES / ".build"
    work.mkdir(parents=True, exist_ok=True)
    source = work / "note.txt"
    source.write_text(
        "Quarterly report\n\n"
        "Document routing reached the measured targets.\n"
        "Total: 120 units.\n"
    )
    subprocess.run(
        [
            SOFFICE,
            f"-env:UserInstallation=file://{work}/lo",
            "--headless",
            "--convert-to",
            "pdf",
            "--outdir",
            str(FIXTURES),
            str(source),
        ],
        check=True,
        capture_output=True,
    )
    (FIXTURES / "note.pdf").replace(FIXTURES / "note.pdf")
    # Rasterise the text page and wrap the image as a one-page PDF: no text
    # layer, so anydoc reports NeedsOcr and the router falls back.
    note = FIXTURES / "note.pdf"
    image = work / "page.png"
    subprocess.run([SIPS, "-s", "format", "png", str(note), "--out", str(image)], check=True, capture_output=True)
    subprocess.run(
        [SIPS, "-s", "format", "pdf", str(image), "--out", str(FIXTURES / "scanned.pdf")],
        check=True,
        capture_output=True,
    )
    shutil.rmtree(work)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--corpora", required=True, help="path to the benchmark's vendor/ directory")
    args = ap.parse_args()
    corpora = Path(args.corpora)

    FIXTURES.mkdir(parents=True, exist_ok=True)
    for name, relative in TIKA_FIXTURES.items():
        source = corpora / "tika" / relative
        if not source.exists():
            print(f"missing fixture source {source}", file=sys.stderr)
            return 1
        shutil.copyfile(source, FIXTURES / name)

    build_generated()

    manifest = {
        "schema": "operator-doc-router-fixtures/1",
        "files": {
            name: {
                "sha256": sha256(FIXTURES / name),
                "origin": (
                    "apache/tika test resources (Apache-2.0)"
                    if name in TIKA_FIXTURES
                    else "generated by bench/doc-router/make_fixtures.py"
                ),
            }
            for name in [*TIKA_FIXTURES, "note.pdf", "scanned.pdf"]
        },
    }
    (FIXTURES / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
    print(f"wrote {len(manifest['files'])} fixtures to {FIXTURES}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
